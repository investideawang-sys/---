import heapq

def reconstruct_path(prev, start, end):
    if prev[end] == -1 and end != start:
        return []  # пути нет
    path = []
    cur = end
    while cur != -1:
        path.append(cur)
        cur = prev[cur]
    path.reverse()
    if not path or path[0] != start:
        return []
    return path


# --- Вариант 1: матрица смежности ---
def dijkstra_matrix(adj_matrix, start):
    n = len(adj_matrix)
    dist = [float('inf')] * n
    prev = [-1] * n
    dist[start] = 0

    pq = [(0, start)]
    visited = [False] * n

    while pq:
        d, u = heapq.heappop(pq)
        if visited[u]:
            continue
        visited[u] = True

        for v in range(n):
            weight = adj_matrix[u][v]
            # Пропускаем отсутствующие рёбра: None или inf
            if weight is None or weight == float('inf'):
                continue
            if dist[u] + weight < dist[v]:
                dist[v] = dist[u] + weight
                prev[v] = u
                heapq.heappush(pq, (dist[v], v))

    return dist, prev


# --- Вариант 2: список смежности ---
def dijkstra_adj_list(adj, start):
    n = len(adj)
    dist = [float('inf')] * n
    prev = [-1] * n
    dist[start] = 0

    pq = [(0, start)]
    visited = [False] * n

    while pq:
        d, u = heapq.heappop(pq)
        if visited[u]:
            continue
        visited[u] = True

        for v, weight in adj[u]:
            if dist[u] + weight < dist[v]:
                dist[v] = dist[u] + weight
                prev[v] = u
                heapq.heappush(pq, (dist[v], v))

    return dist, prev



import networkx as nx
import random

# --- Входные параметры (подставить значения от преподавателя) ---
n = 45      # количество вершин
p = 0.75      # вероятность появления ребра
seed = 42    # для воспроизводимости
random.seed(seed)

# --- Создание пустого графа ---
graph = nx.Graph()
graph.add_nodes_from(range(n))  # вершины 0..n-1

# --- Ручная генерация рёбер по модели Эрдёша–Реньи ---
for i in range(n):
    for j in range(i + 1, n):  # каждая пара (i, j) ровно один раз
        if random.random() < p:
            graph.add_edge(i, j)

# --- Вычисления ---
# 1. Эмпирическая средняя степень вершины
degrees = dict(graph.degree())          # {вершина: степень}
total_degree = sum(degrees.values())    # сумма всех степеней
avg_degree_empirical = total_degree / n # средняя степень по графу

# 2. Теоретическая средняя степень (по формуле из лекций)
avg_degree_theoretical = (n - 1) * p

# --- Вывод результатов ---
print(f"Параметры: n = {n}, p = {p}")
print(f"Средняя степень (эмпирическая): {avg_degree_empirical:.4f}")
print(f"Средняя степень (теоретическая): {avg_degree_theoretical:.4f}")
print(f"Разница: {abs(avg_degree_empirical - avg_degree_theoretical):.4f}")